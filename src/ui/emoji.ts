export function dishEmoji(r: Pick<Recipe, 'name'>): string {
  for (const [re, e] of DISH) if (re.test(r.name)) return e;
  return '🍽️';
}

/** Мягкий фон плитки по типу блюда. */
export function dishTone(type: RecipeType): string {
  switch (type) {
    case 'breakfast':
      return 'tone-sun';
    case 'batch_lunch':
      return 'tone-soup';
    case 'weekend':
      return 'tone-rose';
    case 'backup':
      return 'tone-gray';
    default:
      return 'tone-leaf';
  }
}

