/** Приём пищи без рецепта: сколько обычно съедают. */
const BY_MEAL: Record<string, number> = { завтрак: 400, обед: 600, ужин: 600, перекус: 200 };
/** Блюдо по рецепту: порция по типу рецепта. */
const BY_TYPE: Record<string, number> = { breakfast: 450, batch_lunch: 650, dinner: 650, weekend: 750, backup: 550, extra: 500 };

/**
 * Калории полного приёма пищи (≈ треть суточной нормы). Суточную норму посчитали по росту,
 * весу и полу (Mifflin–St Jeor × 1,4 — обычная активность); здесь только итог.
 */
const MEAL_KCAL: Record<string, number> = { Крис: 730, Кристина: 570 };

/** Калории продукта: сколько штук или граммов взяли. */
export function productKcal(key: string, amount: number): number {
  const p = PRODUCT_BY_KEY.get(key);
  const per = KCAL[key] ?? 150;
  return p?.unit === 'шт' ? per * amount : (per * amount) / 100;
}

/** Калории записи «Съели»: сохранённые на телефоне → по рецепту → по словам в названии → по приёму пищи. */
export function kcalOf(row: EatenRow, recipes: Recipe[], known: Record<string, number> = {}): number {
  if (known[row.id]) return known[row.id];
  const recipe = row.recipeId ? recipes.find((r) => r.id === row.recipeId) : undefined;
  if (recipe) return BY_TYPE[recipe.type] ?? 600;
  const name = normalize(row.dish ?? '');
  let sum = 0;
  for (const [w, k] of DISH_WORDS) if (name.includes(w)) sum += k;
  // «Банан» как продукт из каталога
  if (!sum) {
    const key = productKeyOf(row.dish ?? '');
    if (key && KCAL[key] && PRODUCT_BY_KEY.get(key)?.unit === 'шт') sum = KCAL[key];
  }
  if (sum) return Math.min(1400, sum);
  return BY_MEAL[row.meal] ?? 500;
}

/** Сколько сытости (в процентах) дают эти калории этому человеку. */
export function gainOf(kcal: number, person: string): number {
  const meal = MEAL_KCAL[person] ?? 650;
  return Math.max(3, Math.min(110, Math.round((kcal / meal) * 100)));
}
